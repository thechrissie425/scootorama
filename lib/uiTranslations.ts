export type SupportedLanguage = keyof typeof uiTranslations
export type TranslationKey = keyof typeof uiTranslations.en

// Enhanced translation function with fallbacks
export function translate(lang: string, key: TranslationKey): string {
  const language = lang as SupportedLanguage

  // Return translation for the requested language
  if (uiTranslations[language]?.[key]) {
    return uiTranslations[language][key]
  }

  // Fallback to English
  if (uiTranslations.en[key]) {
    return uiTranslations.en[key]
  }

  // Final fallback - return the key itself
  return key
}

// Auto-expand translations using API
export async function autoTranslateUIStrings(newKeys: Record<string, string>) {
  try {
    const response = await fetch('/api/auto-translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        type: 'ui-strings',
        sourceLanguage: 'en',
        targetLanguages: ['de', 'fr', 'es', 'ja'],
        strings: newKeys,
      }),
    })

    const result = await response.json()
    return result
  } catch (error) {
    console.error('Failed to auto-translate UI strings:', error)
    return null
  }
}

// React Hook for UI translations
export function useUITranslation(language: string) {
  return {
    t: (key: TranslationKey) => translate(language, key),
    language: language as SupportedLanguage,
  }
}
